"""Safety-invariant fuzzing evidence: 50,000 random honest and hostile steps on the real code, plus deliberate bugs.

Writes docs/evidence/fuzzing_report.json (the app's Proof screen reads it) and docs/evidence/safety_fuzzing_evidence.md.

    python scripts/fuzz_safety_invariants.py            # 50,000 steps, seed 42
    python scripts/fuzz_safety_invariants.py 10000 7    # steps, seed
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.setdefault("SATHI_LLM_ENABLED", "0")
os.environ.setdefault("WHATSAPP_MODE", "off")
os.environ.setdefault("SATHI_FX_MODE", "fixture")

from app.security.fuzzer import run_invariant_fuzzer  # noqa: E402
from app.security.mutants import MUTANTS  # noqa: E402

OUT = ROOT.parent / "docs" / "evidence"


def main(iterations: int = 50000, seed: int = 42) -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    print(f"Fuzzing the real code: {iterations:,} steps, seed {seed} …")
    clean = run_invariant_fuzzer(iterations=iterations, seed=seed)
    print(f"  {clean.violations_detected} violations, {clean.payments_completed} payments went through, "
          f"{clean.refusals:,} refusals, {clean.duration_seconds}s")
    mutants = []
    for name, (mutant, expected) in sorted(MUTANTS.items()):
        with mutant():
            m = run_invariant_fuzzer(iterations=5000, seed=seed)
        first = next((v for v in m.first_violations), None)
        caught = {k for k, v in m.invariant_status.items() if v["violations"]}
        mutants.append({"mutant": name, "doc": (mutant.__doc__ or "").strip(), "expected": expected,
                        "caught": expected in caught, "invariants_hit": sorted(caught),
                        "first_seen_at_step": first["step"] if first else None})
        print(f"  mutant {name}: {'caught' if expected in caught else 'MISSED'} at step {first['step'] if first else '-'}")
    report = {**clean.to_dict(), "mutants": mutants}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "fuzzing_report.json").write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    rows = "\n".join(f"| `{k}` | {v['desc']} | {v['violations']} |" for k, v in clean.invariant_status.items())
    vectors = "\n".join(f"| {k.replace('_', ' ')} | {n:,} |" for k, n in clean.attacks_by_vector.items())
    mrows = "\n".join(f"| `{m['mutant']}` | {m['doc']} | {'caught' if m['caught'] else '**missed**'} "
                      f"(step {m['first_seen_at_step']}) |" for m in mutants)
    md = f"""# Safety-invariant fuzzing

Generated by `backend/scripts/fuzz_safety_invariants.py` on {clean.timestamp} (seed {clean.seed}).

**{clean.total_attacks:,} random steps, {clean.hostile_steps:,} of them attacks: {clean.violations_detected} violations.**
Money still moves: {clean.payments_completed} payments went through ({clean.payments_under_mandate} by the autopilot under a
signed mandate, the rest approved with passkeys), and {clean.refusals:,} unsafe or invalid requests were refused.
Run time {clean.duration_seconds}s ({clean.attacks_per_second:,.0f} steps a second). No AI model is called.

## How it works

Each step picks an action and a random person (parent, student or the agent) with random arguments: honest use
(draft, sign with the phone's passkey, send with an Idempotency-Key, let days pass so transfers land and the autopilot
runs, write and sign a family mandate) mixed with attacks. After **every** step the invariants below are checked
against the real state: the bank's double-entry books, the drafts and their approvals, and the hash-chained log.

| Invariant | Rule | Violations |
|---|---|---|
{rows}

## Attacks and actions tried

| Vector | Times |
|---|---|
{vectors}

## Does the fuzzer have teeth? Deliberate bugs

A "0 violations" result only means something if the fuzzer would have caught a bug. Each mutant breaks one rule on
purpose (only during its own run); the fuzzer must catch it.

| Mutant | The bug | Result |
|---|---|---|
{mrows}

## A real gap it found

The first run of this fuzzer found one: SMS that the inbox ignored as "not about money" were never labelled for
taint tracking, so an amount planted in such a message could reach a payment the agent drafted. Fixed by labelling
the amounts of all outside text at the door, before any filtering (`app/inbox/service.py`), with a regression test.
"""
    (OUT / "safety_fuzzing_evidence.md").write_text(md, encoding="utf-8")
    print(f"Wrote {OUT / 'fuzzing_report.json'} and safety_fuzzing_evidence.md")


if __name__ == "__main__":
    args = [int(a) for a in sys.argv[1:3]]
    main(*args)
