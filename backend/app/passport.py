"""Payment passport: a verifiable on-time payment record for credit building (Topic C names it).

International students arrive with no local credit history (problem P-31). The passport lists
payments that really went through Bluefin (tuition, living-money transfers, renewals done on time).
Each entry points to its entry in the hash-chained audit log, and the whole passport is signed (HMAC).
A landlord or bank can check it: tampered, expired, revoked or fabricated passports fail.

Honest limits (shown on the passport):
  * it is NOT an official credit score or a PBOC credit report;
  * in this sandbox it only covers payments made through Bluefin.
"""
from __future__ import annotations

import hashlib
import hmac
import json
from datetime import datetime, timedelta
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from app.service import AppState

VALID_DAYS = 90
DISCLAIMER = ("Payment record generated by Bluefin from its tamper-evident activity log. Not an official credit score "
              "or credit report. Sandbox demo: covers only payments made through Bluefin.")


PRESENTATION_KEYS = ("verify_url", "qr_svg")  # added for display after signing; not part of the signature


def qr_svg(url: str) -> str:
    import io

    import qrcode
    import qrcode.image.svg

    buf = io.BytesIO()
    qrcode.make(url, image_factory=qrcode.image.svg.SvgPathImage, border=2).save(buf)
    svg = buf.getvalue().decode("utf-8")
    return svg[svg.index("<svg"):]  # drop the XML declaration for mobile SVG renderers


def _canonical(obj: dict) -> bytes:
    return json.dumps(obj, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode("utf-8")


def build_entries(app: "AppState", include_amounts: bool) -> list[dict]:
    arrivals = {e["data"]["transfer_id"]: e for e in app.audit.entries if e["event"] == "transfer_arrived"}
    out = []
    for e in app.audit.entries:
        if e["seq"] <= app.session_start_seq:
            continue  # earlier sandbox sessions: their ids may collide with this session's
        if e["event"] == "transfer_sent":
            d = e["data"]
            spec = app.specs.get(d["draft_id"])
            arrived = arrivals.get(d["transfer_id"])
            arrived_at = arrived["data"]["arrived_at"][:10] if arrived else None
            due = spec.deadline.isoformat() if spec and spec.deadline else None
            on_time = None if not (due and arrived_at) else arrived_at <= due
            out.append({
                "kind": "tuition" if d.get("purpose") == "tuition" else "living_transfer",
                "date": (e["sim_time"] or e["ts"])[:10],
                "payee": "University (verified official account)" if d.get("purpose") == "tuition" else "Own account in China",
                "amount_cny": d["amount_cny"] if include_amounts else None,
                "due": due, "arrived": arrived_at, "on_time": on_time,
                "audit_seq": e["seq"], "audit_hash": e["hash"],
            })
        elif e["event"] == "renewal_completed":
            d = e["data"]
            done = (e["sim_time"] or e["ts"])[:10]
            out.append({
                "kind": "renewal", "date": done, "payee": f"{d['item'].replace('_expiry', '').replace('_', ' ').title()} renewed",
                "amount_cny": None, "due": d["old_expiry"], "arrived": done, "on_time": done <= d["old_expiry"],
                "audit_seq": e["seq"], "audit_hash": e["hash"],
            })
    return out


def issue(app: "AppState", secret: bytes, passport_id: str, include_amounts: bool) -> dict:
    entries = build_entries(app, include_amounts)
    with_due = [x for x in entries if x["on_time"] is not None]
    on_time = sum(1 for x in with_due if x["on_time"])
    months = sorted({x["date"][:7] for x in entries})
    now = app.now
    body = {
        "id": passport_id,
        "holder": {"name": app.profile["student_name"], "university": app.profile["university"],
                   "corridor": app.corridor.name},
        "issued_at": now.isoformat(),
        "valid_until": (now + timedelta(days=VALID_DAYS)).isoformat(),
        "include_amounts": include_amounts,
        "stats": {
            "payments": sum(1 for x in entries if x["kind"] != "renewal"),
            "renewals": sum(1 for x in entries if x["kind"] == "renewal"),
            "with_deadline": len(with_due), "on_time": on_time,
            "on_time_pct": round(100 * on_time / len(with_due)) if with_due else None,
            "months_active": len(months), "first": months[0] if months else None, "last": months[-1] if months else None,
            "total_cny": (str(sum(float(x["amount_cny"]) for x in entries if x["amount_cny"])) if include_amounts else None),
        },
        "entries": entries,
        "audit_chain_head": app.audit.last_hash,
        "disclaimer": DISCLAIMER,
    }
    body["signature"] = hmac.new(secret, _canonical(body), hashlib.sha256).hexdigest()
    return body


def verify(app: "AppState", secret: bytes, passport: dict, revoked: set[str]) -> dict:
    reasons = []
    sig = passport.get("signature", "")
    unsigned = {k: v for k, v in passport.items() if k not in ("signature", *PRESENTATION_KEYS)}
    if not hmac.compare_digest(hmac.new(secret, _canonical(unsigned), hashlib.sha256).hexdigest(), sig):
        reasons.append("signature does not match: the passport was changed or not issued by Bluefin")
    if passport.get("id") in revoked:
        reasons.append("revoked by the holder")
    try:
        if datetime.fromisoformat(passport["valid_until"]) < app.now:
            reasons.append("expired")
    except (KeyError, ValueError):
        reasons.append("missing validity date")
    by_seq = {e["seq"]: e for e in app.audit.entries}
    for x in passport.get("entries", []):
        if by_seq.get(x.get("audit_seq"), {}).get("hash") != x.get("audit_hash"):
            reasons.append(f"entry from {x.get('date')} is not in the activity log")
            break
    if not app.audit.verify()["valid"]:
        reasons.append("the activity log itself has been tampered with")
    return {"valid": not reasons, "reasons": reasons, "id": passport.get("id"),
            "holder": passport.get("holder"), "stats": passport.get("stats")}
